import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createGenerator } from 'ts-json-schema-generator';

import { generateComponentArray, generateImports, generateRegistry } from './registry/generator.js';
import { createComponentSources } from './registry/sources.js';

import { createLogger } from './logger.js';

const log = createLogger('Registry');

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const PATHS = {
    dedicated: path.join(process.cwd(), 'src/components/dedicated'),
    primitives: path.join(process.cwd(), 'src/components/primitives/LayoutPrimitives.tsx'),
    output: path.join(process.cwd(), 'src/components-registry.ts'),
    outputSchema: path.join(__dirname, '../schemas/theme-manifest-schema.json'),
    tempTypes: path.join(process.cwd(), 'src/temp-schema-types.ts'),
    tsconfig: path.join(process.cwd(), 'tsconfig.json')
};

const COMPONENT_SOURCES = createComponentSources(PATHS);

// Resolve all configured component sources
const sources = COMPONENT_SOURCES.map(source => ({
    ...source,
    components: source.getComponents()
}));

const allComponents = sources.flatMap(source => source.components);

const content = [
    '// This file is auto-generated by scripts/build-registry.js',
    '// Do not edit this file manually.',
    '',
    ...generateImports(sources),
    '',
    generateRegistry(allComponents),
    ...sources.map(source => generateComponentArray(source.name, source.components))
].join('\n');

// Avoid unnecessary filesystem writes if the registry hasn't changed
if (fs.existsSync(PATHS.output) && fs.readFileSync(PATHS.output, 'utf8') === content) {
    log.success('Registry is already up to date.');
} else {
    fs.writeFileSync(PATHS.output, content, 'utf8');
    log.success(`Successfully generated components registry at ${PATHS.output} (${allComponents.length} components)`);
}

// VS Code schema generation
log.info('Analyzing TypeScript interfaces for the VS Code Schema...');

// 1. Generate a temporary file exporting all discovered component props
const typeImports = sources.map(source => {
    if (source.name === 'PRIMITIVE_COMPONENTS') {
        const props = source.components.map(c => `${c}Props`).join(', ');
        return `export type { ${props} } from './components/primitives/LayoutPrimitives';`;
    }
    if (source.name === 'DEDICATED_COMPONENTS') {
        return source.components.map(c => 
            `export type { ${c}Props } from './components/dedicated/${c}';`
        ).join('\n');
    }
    return '';
}).join('\n');

fs.writeFileSync(PATHS.tempTypes, typeImports, 'utf8');

const config = {
    path: PATHS.tempTypes,
    tsconfig: PATHS.tsconfig,
    type: "*",
    skipTypeCheck: true,
};

try {
    // 2. Extract AST definitions using ts-json-schema-generator
    const rawSchema = createGenerator(config).createSchema(config.type);

    // 3A. Build dynamic if/then blocks for "components" (triggers on "name")
    const allOfBlocksComponents = allComponents.map(compName => {
        const propsTypeName = `${compName}Props`;
        
        if (!rawSchema.definitions || !rawSchema.definitions[propsTypeName]) {
            return null;
        }

        return {
            if: { properties: { name: { const: compName } } },
            then: { properties: { props: { $ref: `#/definitions/${propsTypeName}` } } }
        };
    }).filter(Boolean);

    // 3B. Build dynamic if/then blocks for "reconstructs" (triggers on "layoutComponent")
    const allOfBlocksReconstructs = allComponents.map(compName => {
        const propsTypeName = `${compName}Props`;
        
        if (!rawSchema.definitions || !rawSchema.definitions[propsTypeName]) {
            return null;
        }

        return {
            if: { properties: { layoutComponent: { const: compName } } },
            then: { properties: { props: { $ref: `#/definitions/${propsTypeName}` } } }
        };
    }).filter(Boolean);

    // 4. Assemble the final VS Code JSON Schema manifest
    const finalVsCodeSchema = {
        $schema: "https://json-schema.org/draft/2020-12/schema",
        title: "SPM Theme Manifest",
        type: "object",
        definitions: rawSchema.definitions,
        properties: {
            targetUrl: { type: "string" },
            version: { type: "string" },
            minEngineVersion: { type: "string" },
            theme: {
                type: "object",
                properties: {
                    label: { type: "string" },
                    author: { type: "string" },
                    description: { type: "string" },
                    tags: { type: "array", items: { type: "string" } },
                    cssVariables: { type: "object", additionalProperties: { type: "string" } },
                    customStyles: { type: "string" },
                    noticeSelector: { type: "string" }
                },
                additionalProperties: false
            },
            components: {
                type: "array",
                items: {
                    type: "object",
                    required: ["name", "selector", "action"],
                    properties: {
                        name: { type: "string" },
                        selector: { type: "string" },
                        action: { enum: ["replace", "append", "hide"] },
                        propsMap: { type: "object", additionalProperties: { type: "string" } },
                        props: { type: "object" } 
                    },
                    allOf: allOfBlocksComponents
                }
            },
            reconstructs: {
                type: "array",
                items: {
                    type: "object",
                    properties: {
                        containerSelector: { type: "string" },
                        layoutComponent: { type: "string" },
                        urlPattern: { type: "string" },
                        propsMap: { type: "object" },
                        props: { type: "object" },
                        children: { type: "array" },
                        preserve: { type: "object" }
                    },
                    allOf: allOfBlocksReconstructs
                }
            }
        },
        additionalProperties: true
    };

    const schemaDir = path.dirname(PATHS.outputSchema);
    if (!fs.existsSync(schemaDir)) {
        fs.mkdirSync(schemaDir, { recursive: true });
    }

    fs.writeFileSync(PATHS.outputSchema, JSON.stringify(finalVsCodeSchema, null, 2), 'utf8');
    log.success(`Successfully generated intelligent JSON schema (${allOfBlocksComponents.length} components, ${allOfBlocksReconstructs.length} reconstructs mapped).`);

} catch (error) {
    log.error("Schema generation failed:", error);
} finally {
    // 5. Clean up temporary types file
    if (fs.existsSync(PATHS.tempTypes)) {
        fs.unlinkSync(PATHS.tempTypes);
    }
}